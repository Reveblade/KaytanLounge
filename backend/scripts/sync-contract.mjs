// Copies src/contract/api.ts into both Next apps. `--check` fails when a copy is stale.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../src/contract/api.ts');
const targets = [
  resolve(here, '../../website/src/lib/contract/api.ts'),
  resolve(here, '../../admin/src/lib/contract/api.ts'),
];
const banner = '// GENERATED by backend/scripts/sync-contract.mjs. Edit backend/src/contract/api.ts instead.\n';
const content = banner + readFileSync(source, 'utf8');
const check = process.argv.includes('--check');
let stale = 0;

for (const target of targets) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`stale: ${target}`);
    stale += 1;
    continue;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  console.log(`synced: ${target}`);
}

if (stale) process.exit(1);
